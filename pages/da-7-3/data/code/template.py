from pathlib import Path

import pandas as pd
import seaborn as sns

folder = Path.cwd()
while not (folder / "data" / "eda").is_dir() and folder != folder.parent:
    folder = folder.parent
raw = pd.read_csv(folder / "data/eda/clients_export.csv")
df = (raw.dropna(subset=["client_id"])
         .drop_duplicates("client_id")
         .query("orders_q1 >= 0 and channel != '-' and spend_q1 < 1e6"))
ax = sns.scatterplot(data=df, x="visits_q1", y="orders_q1", alpha=0.2)
ax.set(xlabel="Визиты за квартал", ylabel="Заказы за квартал")
print(f"Корреляция: {df['visits_q1'].corr(df['orders_q1']):.2f}")
print(f"Заказов на один визит: {df['orders_q1'].sum() / df['visits_q1'].sum():.2f}")

# %% [markdown]
# **Вывод.** Число заказов положительно связано с числом визитов (r = 0,56). По суммам за квартал приходится около одного заказа на четыре визита.
