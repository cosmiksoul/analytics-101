"""Выборки сцены страницы 5.3 «Закон больших чисел и центральная предельная теорема» курса «Аналитика 101».

Тысяча выборок по 30 чеков, по 120 и по 480 из учебных чеков checks.csv — с возвращением, зерно 5300.
Скрипт печатает числа, которые показывает анимация: первые средние, разброс средних против σ/√n,
долю средних в полосе μ ± 500 ₽ и в пределах двух стандартных ошибок.

Запуск из корня папки материалов: python da-5-3-lln-clt/gen_scene.py
Нужен общий набор data/probability/.
"""
import numpy as np
import pandas as pd

amount = pd.read_csv("data/probability/checks.csv")["amount"].to_numpy(np.int64)
mu, sigma = amount.mean(), amount.std()          # 20 000 чеков — вся совокупность
print(f"чеки: μ = {mu:.0f} ₽, σ = {sigma:.0f} ₽, медиана {np.median(amount):.0f} ₽, от {amount.min()} до {amount.max()} ₽")

rng = np.random.default_rng(5300)
samples = {n: rng.choice(amount, size=(1000, n)) for n in (30, 120, 480)}   # порядок вызовов важен: 30, 120, 480
means = {n: s.mean(axis=1) for n, s in samples.items()}

first = samples[30][0]
print(f"первая выборка из 30 чеков: среднее {first.mean():.0f} ₽, два самых крупных чека {np.sort(first)[-2:].tolist()}")
print("первые четыре средних:", np.round(means[30][:4]).astype(int).tolist())
print(f"первые 100 выборок: наибольшее среднее {means[30][:100].max():.0f} ₽, среднее средних {means[30][:100].mean():.2f} ₽ при μ = {mu:.2f}")
print(f"вся тысяча: наибольшее среднее {means[30].max():.0f} ₽")

print("    n  разброс средних   σ/√n  в полосе μ ± 500 ₽")
for n, m in means.items():
    print(f"{n:>5} {m.std():14.0f} {sigma / np.sqrt(n):8.0f} {np.mean(np.abs(m - mu) <= 500):12.1%}")

se = sigma / np.sqrt(480)
print(f"n = 480: μ ± 2·σ/√n = ± {2 * se:.0f} ₽, внутри {np.mean(np.abs(means[480] - mu) <= 2 * se):.1%} средних")

