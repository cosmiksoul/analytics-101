# Распакуйте архив главы так, чтобы папка `data/` находилась рядом с папкой урока. В `data/unit/` должны лежать `clients.csv`, `orders.csv`, `activity.csv` и `marketing_spend.csv`. Первая ячейка найдёт папку с материалами и сделает её рабочей. В ней появится график `tails.svg`.

# %% code
import os
import pathlib
import platform

import matplotlib
import pandas as pd
import scipy

root = pathlib.Path.cwd()
while not (root / "data" / "unit").is_dir() and root != root.parent:
    root = root.parent                      # поднимаемся, пока рядом не окажется data/unit/
assert (root / "data" / "unit" / "orders.csv").exists(), \
    "Не найдена папка data/unit/. Скачайте общий набор темы 10 и положите data/ рядом с папкой страницы"
os.chdir(root)

print("Python", platform.python_version(), "| pandas", pd.__version__, "| SciPy", scipy.__version__,
      "| matplotlib", matplotlib.__version__)

