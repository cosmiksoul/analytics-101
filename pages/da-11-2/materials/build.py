"""Материалы страницы 11.2: ноутбук с размером выборки и шаблон документа дизайна теста.
Данные — общий набор data/ab (тема 11)."""
import re


def build(m):
    m.use_data("ab")
    m.versions = "Код проверен на Python 3.13, pandas 3.0, NumPy 2.5, SciPy 1.18, statsmodels 0.15 и pyarrow 26."

    m.notebook("sample_size.ipynb", "sample_size.nb.py", "main")
    m.from_reader_folder("sample_size.ipynb")
    out = m.page_out("manual") + "\n" + m.page_out("sm") + "\n" + m.page_out("sim")
    m.check("в выводе: MDE 0,86 п. п. из 5,78 млн ₽ в год, 26 329 человек в группе вручную и 26 327 в statsmodels, выручке нужно в 7,7 раза больше",
            all(x in out for x in ("пункт конверсии: 5.78 млн ₽ в год → MDE = 0.86 п. п. = +6.1%", "конверсия: 26329 в группе", "конверсия, h = 0.0244:  26327 в группе",
                                   "выручка (+61 ₽): 201535 в группе — в 7.7 раза больше")))
    m.check("в выводе симуляции: A/A значимы в 4,5%, эффект MDE находят в 81,2% тестов",
            "конверсия, 26329 в группе: A/A значимы 4.5%, A/B с эффектом MDE — 81.2%" in out)

    # шаблон документа дизайна: пустая таблица и заполненный блок страницы
    doc = m.page_code("doc").rstrip("\n")
    fields = re.findall(r"^(?:(\d+)\. )?([А-ЯЁ][а-яё]+(?: [а-яё]+)?) {2,}\S", doc, flags=re.M)
    names = [f[1] for f in fields]
    want = ["Что меняем", "Гипотеза", "Метрики", "MDE", "Статистика", "Выборка", "Рандомизация", "Срок", "Решение", "Проверки", "После старта"]
    found = [n for n in want if re.search(rf"^(?:\d+\. )?{re.escape(n)}\b", doc, flags=re.M)]
    m.check("в блоке страницы 11 полей документа дизайна", found == want, f"{found} {names}")
    hints = {
        "Что меняем": "одно изменение и решение, которое примут по тесту: внедрить или нет",
        "Гипотеза": "метрика, направление и размер: с какого значения до какого, за какой срок; что не должно ухудшиться",
        "Метрики": "одна целевая с точным определением; вторичные — откуда взялся эффект; защитные — допустимые потери и критерий проверки",
        "MDE": "эффект, на который рассчитывают выборку; единицы измерения, уровень значимости, мощность и связь с порогом окупаемости",
        "Статистика": "тест, сторона, α и мощность; в каком виде будет результат",
        "Выборка": "людей в группе и всего",
        "Рандомизация": "единица, доли групп, доля трафика, правило назначения группы, что считается показом",
        "Срок": "целые недели с датами; за сколько дней набирается план при ожидаемом потоке",
        "Решение": "когда смотрим и при каком результате внедряем",
        "Проверки": "результаты A/A-теста, контроль численности групп и полноты записей",
        "После старта": "как документировать отклонения от плана",
    }
    md = ("# Документ дизайна A/B-теста\n\n"
          "Шаблон из урока 11.2 «Как спланировать A/B-тест» курса «Аналитика 101». Зафиксируйте план до запуска. Все последующие отклонения укажите в отчёте. "
          "Скопируйте таблицу и замените подсказки во втором столбце своими ответами.\n\n"
          "## Пустой шаблон\n\n| поле | что записать |\n|---|---|\n" + "".join(f"| {n} | {hints[n]} |\n" for n in want) +
          "\n## Заполненный пример: checkout_v2\n\nТак документ выглядит на странице — для учебного теста нового оформления заказа.\n\n```\n" + doc + "\n```\n")
    m.put("test_design_template.md", md)
    m.check("test_design_template.md: пустая таблица из тех же 11 полей и заполненный блок страницы дословно",
            all(f"| {n} |" in md for n in want) and doc in md)
