# ### Упражнение 5. Ловушка с формой
#
# Ниже прогноз трат `pred` случайно стал столбцом формы (1000, 1), как в блоке про broadcasting. Запишите в `bad_shape` форму массива `spend - pred`, а в `mae` — настоящую среднюю абсолютную ошибку прогноза в рублях.

# %% code
X1 = np.c_[np.ones(len(df)), df["income"], df["orders"]]
w = np.array([205, 0.0347, 2550])
spend = df["spend"].to_numpy()             # (1000,)
pred = (X1 @ w).reshape(-1, 1)             # (1000, 1)
print(spend.shape, pred.shape)

# %% exercise
bad_shape = ...   # ваш код: форма spend - pred
mae = ...         # ваш код: средняя абсолютная ошибка, ₽

# %% solution
bad_shape = (spend - pred).shape                    # (1000,) − (1000, 1) → таблица всех пар
mae = np.abs(spend - pred.ravel()).mean()           # ravel возвращает прогнозу форму (1000,)
print(bad_shape, round(float(mae)))

# %% check
assert bad_shape == (1000, 1000), f"(1000,) минус (1000, 1) даёт таблицу (1000, 1000); получено {bad_shape}"
assert isinstance(mae, (int, float, np.floating)) and round(float(mae)) == 3017, f"Настоящая ошибка — 3 017 ₽; получено {mae}. 7 532 ₽ — это среднее по миллиону чужих пар"
print("Упражнение 5: верно")

# %% [markdown] solutions
# **Разбор.** Вектор (1000,) встаёт строкой, столбец (1000, 1) — столбцом, и разность считается для каждой пары «траты клиента i, прогноз клиента j». Ошибки нет, а среднее по миллиону таких пар — 7 532 ₽ вместо 3 017 ₽. Лекарства два: вернуть прогнозу форму (1000,) через `ravel()` или сделать столбцом и траты. Привычка, которая ловит такие ошибки, — смотреть `.shape` после каждой операции с массивами разных форм.
