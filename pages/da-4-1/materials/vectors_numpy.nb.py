# %% [markdown] solutions
# **Разбор.** Номер оси говорит, какое измерение исчезнет из формы. У `X` форма (1000, 3): `axis=0` убирает первую длину, остаётся (3,), `axis=1` убирает вторую, остаётся (1000,). Наибольшее число в каждой строке — доход: в рублях он заслоняет остальные признаки, как на странице.

# %% [markdown]
# ### Упражнение 2. Строки длины 1
#
# Соберите матрицу `U`: каждая строка `Z`, делённая на свою длину. У всех строк `U` длина должна быть равна 1 — от клиента остаётся одно направление.

# %% exercise
U = ...   # ваш код: (1000, 3) делим на длины строк

# %% solution
length = np.linalg.norm(Z, axis=1)      # длины строк, форма (1000,)
U = Z / length[:, None]                 # (1000, 3) / (1000, 1): столбец длин растягивается вправо
print(U.shape, np.linalg.norm(U, axis=1)[:4])

# %% check
assert getattr(U, "shape", None) == (1000, 3), f"U должна остаться матрицей (1000, 3); получено {getattr(U, 'shape', None)}"
assert np.allclose(np.linalg.norm(U, axis=1), 1), "Длина каждой строки U должна быть 1: разделите строку на её длину, а не столбец на его длину"
assert np.allclose(U[48], [0.526, 0.626, 0.576], atol=1e-3), f"Строка клиента 49 должна быть (0,526; 0,626; 0,576); получено {U[48]}"
print("Упражнение 2: верно")

# %% [markdown] solutions
# **Разбор.** Запись `Z / np.linalg.norm(Z, axis=1)` кончается ошибкой `ValueError: operands could not be broadcast together with shapes (1000,3) (1000,)`. Формы сравниваются справа: 3 и 1 000 не равны, и ни одна не единица. Длины надо поставить столбцом — `[:, None]`, `reshape(-1, 1)` или `np.linalg.norm(Z, axis=1, keepdims=True)`. Хуже было бы с квадратной таблицей (3, 3): там деление на (3,) прошло бы молча и разделило столбцы вместо строк.

# %% [markdown]
# ### Упражнение 3. Расстояния от одного клиента до всех
#
# Запишите в `d` расстояния от клиента 49 до каждого из 1 000 клиентов в стандартных единицах — без цикла. В `nearest` положите номера `client_id` трёх ближайших к нему клиентов, не считая его самого.

# %% exercise
d = ...         # ваш код: форма (1000,)
nearest = ...   # ваш код: три номера client_id

# %% solution
d = np.sqrt(((Z - Z[48]) ** 2).sum(axis=1))             # (1000, 3) − (3,), сумма по признакам
order = np.argsort(d)                                   # позиции по возрастанию расстояния
nearest = df["client_id"].to_numpy()[order[1:4]]        # order[0] — сам клиент 49
print(d.shape, d[order[:4]], nearest)

# %% check
assert getattr(d, "shape", None) == (1000,), f"d — по расстоянию на клиента, форма (1000,); получено {getattr(d, 'shape', None)}"
assert d[48] == 0, f"Расстояние от клиента 49 до самого себя — 0; получено {d[48]}"
assert np.allclose(d[[959, 744, 386]], [0.166, 0.268, 0.358], atol=1e-3), "До клиентов 960, 745 и 387 должно быть 0,166, 0,268 и 0,358. Считайте по Z, а не по X"
assert list(nearest) == [960, 745, 387], f"Ближайшие — клиенты 960, 745 и 387; получено {list(nearest)}. Строка 48 — это client_id 49"
print("Упражнение 3: верно")

# %% [markdown] solutions
# **Разбор.** `Z - Z[48]` вычитает вектор (3,) из каждой строки матрицы (1000, 3) — это первая строка таблицы broadcasting на странице. Массив (1000, 1000, 3) здесь не нужен: он понадобился бы для расстояний между всеми парами. Ответ совпал с выводом блока про расстояния. Если считать по `X`, ближайшими окажутся клиенты с тем же доходом, а возраст и заказы не повлияют.

# %% [markdown]
# ### Упражнение 4. Косинус со всеми клиентами одной операцией
#
# Запишите в `cos` косинус угла между стрелкой клиента 49 и стрелкой каждого клиента в стандартных единицах. В `same_side` — сколько клиентов смотрят в ту же сторону, что и клиент 49: у скольких косинус больше нуля.

# %% exercise
cos = ...         # ваш код: форма (1000,)
same_side = ...   # ваш код: целое число

# %% solution
a = Z[48]
cos = Z @ a / (np.linalg.norm(Z, axis=1) * np.linalg.norm(a))   # (1000, 3) @ (3,) → (1000,)
same_side = int((cos > 0).sum())
print(cos.shape, cos[[48, 880, 174, 988]], same_side)

# %% check
assert getattr(cos, "shape", None) == (1000,), f"cos — по числу на клиента, форма (1000,); получено {getattr(cos, 'shape', None)}"
assert np.isclose(cos[48], 1), f"Косинус клиента 49 с самим собой — 1; получено {cos[48]}"
assert np.isclose(cos[880], -0.928, atol=1e-3), f"С клиентом 881 косинус −0,928 (угол 158°); получено {cos[880]}. Поделили на обе длины?"
assert same_side == 461, f"В ту же сторону смотрит 461 клиент; получено {same_side}"
print("Упражнение 4: верно")

# %% [markdown] solutions
# **Разбор.** `Z @ a` — тысяча скалярных произведений, по одному на строку, как `X @ w` на странице. Делим на длину каждой строки и на длину `a`: обе величины формы (1000,) и число, поэтому новые оси не нужны. Знак косинуса совпадает со знаком скалярного произведения, отсюда 461 — то же число, что в последнем шаге анимации. С клиентами 881, 175 и 989 косинусы −0,928, 0,002 и 0,904: углы 158°, 90° и 25°.

