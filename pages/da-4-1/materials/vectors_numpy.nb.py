# **Разбор.** При вычитании (1000,) и (1000, 1) NumPy сопоставляет фактические траты каждого клиента с прогнозами для всех клиентов. Среднее абсолютное значение по миллиону таких разностей равно 7 532 ₽. Чтобы получить ошибку по клиентам, приведите оба массива к одной форме, сохранив порядок строк. Можно вернуть прогнозам форму (1000,) с помощью `ravel()` или представить фактические траты столбцом (1000, 1). Оба способа дают 3 017 ₽.
