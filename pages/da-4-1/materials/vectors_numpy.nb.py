# ### Упражнение 5. Форма массива и ошибка прогноза
#
# Прогнозы `pred` хранятся в столбце формы (1000, 1), а фактические траты `spend` — в массиве формы (1000,). Запишите в `bad_shape` форму результата `spend - pred`. Затем сравните прогноз каждого клиента с его фактическими тратами и сохраните среднюю абсолютную ошибку в `mae`.

# %% code
X1 = np.c_[np.ones(len(df)), df["income"], df["orders"]]
w = np.array([205, 0.0347, 2550])
spend = df["spend"].to_numpy()             # (1000,)
pred = (X1 @ w).reshape(-1, 1)             # (1000, 1)
print(spend.shape, pred.shape)

# %% exercise
bad_shape = ...   # ваш код: форма spend - pred
mae = ...         # ваш код: средняя абсолютная ошибка, ₽

# %% solution
bad_shape = (spend - pred).shape                    # (1000,) − (1000, 1) → таблица всех пар
mae = np.abs(spend - pred.ravel()).mean()           # ravel возвращает прогнозу форму (1000,)
print(bad_shape, round(float(mae)))

# %% check
assert bad_shape == (1000, 1000), f"(1000,) минус (1000, 1) даёт таблицу (1000, 1000); получено {bad_shape}"
assert isinstance(mae, (int, float, np.floating)) and round(float(mae)) == 3017, f"Средняя абсолютная ошибка по клиентам — 3 017 ₽; получено {mae}. 7 532 ₽ получится, если сопоставить траты каждого клиента со всеми прогнозами"
print("Упражнение 5: верно")

