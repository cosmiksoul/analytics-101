# %% [markdown]
# ### Упражнение 2. Строки длины 1
#
# Разделите каждый вектор-строку матрицы `Z` на его длину. Запишите результаты в матрицу `U`. После этой операции каждая строка должна иметь единичную длину и сохранять исходное направление. В учебных данных все строки `Z` ненулевые.

# %% exercise
U = ...   # ваш код: (1000, 3) делим на длины строк

# %% solution
length = np.linalg.norm(Z, axis=1)      # длины строк, форма (1000,)
U = Z / length[:, None]                 # (1000, 3) / (1000, 1): столбец длин растягивается вправо
print(U.shape, np.linalg.norm(U, axis=1)[:4])

# %% check
assert getattr(U, "shape", None) == (1000, 3), f"U должна остаться матрицей (1000, 3); получено {getattr(U, 'shape', None)}"
assert np.allclose(np.linalg.norm(U, axis=1), 1), "Длина каждой строки U должна быть 1: разделите строку на её длину, а не столбец на его длину"
assert np.allclose(U[48], [0.526, 0.626, 0.576], atol=1e-3), f"Строка клиента 49 должна быть (0,526; 0,626; 0,576); получено {U[48]}"
print("Упражнение 2: верно")

# %% [markdown] solutions
# **Разбор.** У матрицы `Z` форма (1000, 3), у массива длин — (1000,). При делении формы сравниваются справа, и размеры 3 и 1000 несовместимы. Для деления каждой строки на её длину представьте длины столбцом формы (1000, 1) с помощью `[:, None]` или `reshape(-1, 1)`. Ещё один способ — вычислить длины с `keepdims=True`. Для квадратной матрицы (3, 3) деление на (3,) выполнилось бы, но каждый столбец разделился бы на свой элемент массива длин.

# %% [markdown]
# ### Упражнение 3. Расстояния от одного клиента до всех
#
# Запишите в `d` расстояния от клиента 49 до каждого из 1 000 клиентов в стандартных единицах — без цикла. В `nearest` запишите идентификаторы `client_id` трёх ближайших к нему клиентов, не считая его самого.

# %% exercise
d = ...         # ваш код: форма (1000,)
nearest = ...   # ваш код: три номера client_id

# %% solution
d = np.sqrt(((Z - Z[48]) ** 2).sum(axis=1))             # (1000, 3) − (3,), сумма по признакам
order = np.argsort(d)                                   # позиции по возрастанию расстояния
nearest = df["client_id"].to_numpy()[order[1:4]]        # order[0] — сам клиент 49
print(d.shape, d[order[:4]], nearest)

# %% check
assert getattr(d, "shape", None) == (1000,), f"d — по расстоянию на клиента, форма (1000,); получено {getattr(d, 'shape', None)}"
assert d[48] == 0, f"Расстояние от клиента 49 до самого себя — 0; получено {d[48]}"
assert np.allclose(d[[959, 744, 386]], [0.166, 0.268, 0.358], atol=1e-3), "До клиентов 960, 745 и 387 должно быть 0,166, 0,268 и 0,358. Считайте по Z, а не по X"
assert list(nearest) == [960, 745, 387], f"Ближайшие — клиенты 960, 745 и 387; получено {list(nearest)}. Строка 48 — это client_id 49"
print("Упражнение 3: верно")

# %% [markdown] solutions
# **Разбор.** Выражение `Z - Z[48]` вычитает один и тот же вектор формы (3,) из каждой строки матрицы формы (1000, 3). Чтобы сравнить тысячу клиентов с одним, достаточно тысячи разностей векторов. В исходных единицах к клиенту 49 ближе всех клиенты 24 и 674 с таким же доходом. Расстояния до них различаются из-за возраста и числа заказов. После стандартизации тройка ближайших меняется.

# %% [markdown]
# ### Упражнение 4. Косинус угла между вектором клиента и каждой строкой матрицы
#
# Для каждого клиента вычислите косинус угла между его вектором и вектором клиента 49 после стандартизации. Запишите результаты в `cos`. В `same_side` сохраните число строго положительных косинусов. Включите в расчёт сравнение клиента 49 с самим собой.

# %% exercise
cos = ...         # ваш код: форма (1000,)
same_side = ...   # ваш код: целое число

# %% solution
a = Z[48]
cos = Z @ a / (np.linalg.norm(Z, axis=1) * np.linalg.norm(a))   # (1000, 3) @ (3,) → (1000,)
same_side = int((cos > 0).sum())
print(cos.shape, cos[[48, 880, 174, 988]], same_side)

# %% check
assert getattr(cos, "shape", None) == (1000,), f"cos — по числу на клиента, форма (1000,); получено {getattr(cos, 'shape', None)}"
assert np.isclose(cos[48], 1), f"Косинус клиента 49 с самим собой — 1; получено {cos[48]}"
assert np.isclose(cos[880], -0.928, atol=1e-3), f"С клиентом 881 косинус −0,928 (угол 158°); получено {cos[880]}. Поделили на обе длины?"
assert same_side == 461, f"Положительный косинус получился для 461 клиента; получено {same_side}"
print("Упражнение 4: верно")

# %% [markdown] solutions
# **Разбор.** Выражение `Z @ a` даёт по скалярному произведению для каждой из тысячи строк. Делим этот одномерный массив на произведение длин: у массива длин строк форма (1000,), а длина `a` — одно число. Положительных косинусов 461. Это те же векторы, что и в конце анимации. Для клиентов 881, 175 и 989 косинусы равны примерно −0,928, 0,002 и 0,904, а углы — 158°, 89,9° и 25° соответственно.

