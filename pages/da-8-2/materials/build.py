"""Материалы страницы 8.2: ноутбук с тремя блоками раздела «Код» и скрипт с четырьмя рисунками нюансов.
Данные — общий набор data/viz (тема 08)."""

NUANCES = [("nu_zero", "Нюанс 1. Ось столбцов начинается с нуля"),
           ("nu_sort", "Нюанс 2. Столбцы сортируют по значению"),
           ("nu_many", "Нюанс 3. Сколько категорий выдерживает один график"),
           ("nu_dual", "Нюанс 4. Две оси Y рисуют любую связь")]

HEAD = '''"""Четыре рисунка раздела «Нюансы»: ось с нуля, сортировка, число категорий, две оси Y.

Страница 8.2 «Тип графика под вопрос» курса «Аналитика 101».
Запуск из корня папки материалов:
  python da-8-2-chart-types/nuances.py
Нужен общий набор data/viz/ (sales_monthly.csv).

Скрипт сохраняет в рабочую папку nu_zero.svg, nu_sort.svg, nu_many.svg и nu_dual.svg — это рисунки из текста
страницы — и печатает числа, которые стоят в их заголовках и в тексте нюансов. На странице каждый рисунок строит
отдельный скрипт, поэтому здесь перед каждым следующим стоит plt.rcdefaults(): настройки предыдущего не переходят
на следующий.
"""
'''

SAID = """{'UZ': 46.0, 'KZ': 79.3, 'RU': 140.7, 'BY': 150.8} | отношение BY/UZ: 3.28 | отношение длин при оси с 40: 18.5
по алфавиту: ['кешбэк-сервисы', 'колл-центр', 'маркетплейс', 'офлайн-точки', 'партнёры', 'поиск', 'приложение', 'рассылка', 'сайт', 'соцсети']
по убыванию: ['сайт', 'маркетплейс', 'приложение', 'поиск', 'рассылка', 'соцсети', 'партнёры', 'офлайн-точки', 'кешбэк-сервисы', 'колл-центр']
три крупнейших в 2025: ['сайт', 'маркетплейс', 'приложение']
остальные 7 каналов в декабре 2025, млн ₽: 15.8
корреляция уровней: 0.52
корреляция изменений за месяц: 0.31
"""


def build(m):
    m.use_data("viz")
    m.versions = "Код проверен на Python 3.13, NumPy 2.5, pandas 3.0, matplotlib 3.10 и seaborn 0.13."
    code = m.pdir / "data" / "code"

    m.notebook("chart_types.ipynb", "chart_types.nb.py", "main")
    ref = m.alone([code / f"{k}.py" for k in ("q2chart", "facets", "pie2bars")])
    m.pictures("рисунки ноутбука те же, что строят блоки страницы по отдельности", ref,
               ["question_to_chart.svg", "facets.svg", "pie_to_bars.svg"])
    m.from_reader_folder("chart_types.ipynb")

    # nuances.py: четыре скрипта рисунков из data/code/ подряд; вывод записан в хвосте файла
    text = HEAD
    for i, (key, title) in enumerate(NUANCES):
        src = (code / f"{key}.py").read_text("utf-8").rstrip("\n")
        body = src.split("\n", 1)[1]                        # первая строка файла — комментарий «# Нюанс N: …»
        text += f"\n# ===== {title} =====\n" + ("plt.rcdefaults()\n" if i else "") + body + "\n"
    text += "\n# Вывод:\n" + "".join(f"# {l}\n" for l in SAID.strip("\n").split("\n"))
    m.put("nuances.py", text)
    r = m.said("nuances.py")
    ref = m.alone([code / f"{k}.py" for k, _ in NUANCES])
    m.pictures("nuances.py: четыре рисунка те же, что строят скрипты страницы по отдельности", ref,
               [f"{k}.svg" for k, _ in NUANCES])
    out = r.stdout if r else ""
    m.check("nuances.py: Беларусь 150,8 млн ₽ против 46,0 у Узбекистана — в 3,3 раза, а от оси с 40 млн — почти в 19 раз, как на странице",
            "'UZ': 46.0" in out and "'BY': 150.8" in out and "BY/UZ: 3.28" in out and "при оси с 40: 18.5" in out)
    m.check("nuances.py: случайное блуждание с seed 8 коррелирует с выручкой на 0,52 по уровням и на 0,31 по изменениям",
            "корреляция уровней: 0.52" in out and "корреляция изменений за месяц: 0.31" in out)
    m.check("скрипт и ноутбук не оставили рисунки в материалах страницы", not list(m.out.glob("*.svg")))
