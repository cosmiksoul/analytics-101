# Соберите два множества: `march` — бренды из заказов марта 2026 года, `april` — из заказов апреля. Месяц берите срезом `created[:7]`. Затем составьте список `lost`: мартовские бренды, которых нет в апреле, по алфавиту.

# %% exercise
march = ...   # множество брендов из заказов марта
