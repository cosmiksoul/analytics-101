# %% solution
import copy

draft = copy.deepcopy(data)   # копируется вся структура: словарь, список заказов и каждый заказ
print(draft is data, draft["orders"] is data["orders"], draft == data)

# %% check
assert isinstance(draft, dict) and draft is not data, "draft должен быть отдельным словарём, а не вторым именем data"
draft["orders"][0]["amount"] = 0   # правим черновик
assert data["orders"][0]["amount"] == 1200, "Сумма изменилась и в data: копия поверхностная, заказы внутри общие. Выполните ноутбук заново и сделайте глубокую копию"
print("Упражнение 5: верно")

# %% [markdown] solutions
# **Разбор.** `data.copy()` и `dict(data)` копируют только верхний словарь. По ключу `"orders"` в такой копии лежит тот же список, что в оригинале, поэтому правка первого заказа видна через оба имени. `copy.deepcopy` проходит структуру до дна и копирует каждый вложенный объект.
