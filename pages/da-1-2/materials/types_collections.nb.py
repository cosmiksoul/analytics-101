# %% [markdown]
# ### Упражнение 4. Копия: функция, которая портит исходник
#
# Функция `drop_unpaid` удаляет неоплаченные заказы прямо из переданного списка. Получите `paid_orders` — список из четырёх оплаченных заказов — так, чтобы в `orders` остались все пять.
#
# Если проверка скажет, что `orders` стал короче, выполните ноутбук заново с первой ячейки: исходные данные уже испорчены.

# %% code
def drop_unpaid(rows):
    """Удаляет неоплаченные заказы из списка rows и возвращает его же."""
    for o in rows[:]:            # идём по копии, удаляем из самого списка
        if not o["paid"]:
            rows.remove(o)
    return rows

# %% exercise
paid_orders = ...   # ваш код: вызовите drop_unpaid так, чтобы orders не изменился

# %% solution
paid_orders = drop_unpaid(orders.copy())   # функция получает копию и удаляет заказы из неё
print(len(orders), len(paid_orders), paid_orders is orders)

# %% check
assert len(orders) == 5, "orders стал короче: функция получила сам список, а не копию. Выполните ноутбук заново с первой ячейки"
assert isinstance(paid_orders, list), "paid_orders должен быть списком"
assert len(paid_orders) == 4 and all(o["paid"] for o in paid_orders), "В paid_orders должны остаться четыре оплаченных заказа"
print("Упражнение 4: верно")

# %% [markdown] solutions
# **Разбор.** `orders.copy()` — поверхностная копия: новый список с теми же словарями-заказами. Здесь её хватает, потому что функция меняет состав списка, а сами заказы не трогает. Когда меняют то, что лежит внутри, поверхностной копии мало — это упражнение 5.

