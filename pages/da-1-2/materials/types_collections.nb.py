lost = ...    # список: бренды из march, которых нет в april, по алфавиту

# %% solution
march, april = set(), set()          # пустое множество — set(), а не {}: {} — это пустой словарь
for o in orders:
    month = o["created"][:7]
    if month == "2026-03":
        march.add(o["brand"])        # .add() кладёт элемент во множество; повтор ничего не меняет
    elif month == "2026-04":
        april.add(o["brand"])

lost = []
for b in sorted(march):              # sorted даёт алфавитный порядок: у самого множества порядка нет
    if b not in april:
        lost.append(b)
print(sorted(march), sorted(april), lost)

# %% check
assert march == {"Сова", "Кедр", "Луч"}, f"В марте покупали три бренда, получено {march!r}"
assert april == {"Сова"}, f"В апреле покупали один бренд, получено {april!r}"
assert lost == ["Кедр", "Луч"], f"Ожидался список ['Кедр', 'Луч'], получено {lost!r}"
print("Упражнение 3: верно")

