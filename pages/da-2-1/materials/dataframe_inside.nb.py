# %% [markdown]
# ### Упражнение 5. Числа, которые пришли строками
#
# Столбец `raw` прочитан из файла текстом: в одной сумме пробел между разрядами, вместо другой стоит «н/д». Получите числовой столбец `fixed` типа `float64`, где «н/д» стало пропуском, и сумму известных значений `total`.

# %% code
raw = pd.Series(["3 430", "400", "н/д", "1 300"])
print(raw.dtype, raw.sum())

# %% exercise
fixed = ...   # ваш код: убрать пробелы и перевести в числа
total = ...   # ваш код: сумма известных значений

# %% solution
fixed = pd.to_numeric(raw.str.replace(" ", ""), errors="coerce")   # errors="coerce": нечисловое станет NaN
total = fixed.sum()                                                # sum() пропуски обходит
print(fixed.tolist(), fixed.dtype, total)

# %% check
assert isinstance(fixed, pd.Series) and fixed.dtype == "float64", "fixed должен быть столбцом типа float64"
assert fixed.isna().sum() == 1, "На месте «н/д» должен стоять один пропуск NaN"
assert total == 5130, f"Сумма известных значений — 5 130, получено {total!r}"
print("Упражнение 5: верно")

# %% [markdown] solutions
# **Разбор.** Одного нечислового значения хватает, чтобы весь столбец остался текстом, и тогда `sum()` склеивает строки. `pd.to_numeric` с `errors="coerce"` переводит то, что переводится, а остальное заменяет на `NaN`. Тип получился `float64`, а не `int64`: `NaN` — значение с плавающей точкой, в целочисленном столбце NumPy ему нет места.
